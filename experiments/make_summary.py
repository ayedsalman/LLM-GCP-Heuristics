"""Collect the revision results into results/revision/SUMMARY.md (tables only;
the interpretation for the paper is the authors' call)."""

from __future__ import annotations

import json
import os

import common
import pandas as pd

O = common.OUT


def rd(name, **kw):
    p = os.path.join(O, name)
    return pd.read_csv(p, **kw) if os.path.exists(p) else None


def md(df, floatfmt=".3f"):
    if df is None or len(df) == 0:
        return "_not run_\n"
    return df.to_markdown(index=False, floatfmt=floatfmt) + "\n"


def main():
    S = ["# Revision results (generated by experiments/make_summary.py)\n",
         "All numbers come from the scripts in `experiments/`. VAL is the regenerated "
         "Table-4 suite (seed 42), used for development only; TEST-A (fresh, same design), "
         "TEST-B (balanced, degree-matched) and PLANTED (chi known) are held out. DSATUR = "
         "the paper's `sat*10000 + deg`. Paired tests: bootstrap 95% CI, Wilcoxon + Holm, "
         "TOST with delta = 0.10 colours.\n"]

    e0 = rd("e0_equivalence_summary.csv")
    S += ["## S0.1 Equivalence of the new evaluator\n",
          "A = original code vs incremental (identical colour of every vertex); B = independent "
          "full-argmax reference vs incremental; C = numba engine vs exact engine (colour counts).\n",
          md(e0, ".0f")]

    rep = rd("table7_reproduction_VAL.csv")
    S += ["## Reproduction of Table 7 on the regenerated suite (VAL)\n", md(rep, ".2f")]

    m = rd("seq_means_by_set_scale.csv")
    if m is not None:
        keep = ["set", "scale", "DSATUR", "LLaMA_H3", "Claude_H3A2A", "GPT4o_H4", "DeepSeek_H1", "DeepSeek_H1A",
                "GPT51_H1", "RLF", "RLF_legacy", "DSATUR_brelaz", "DSATUR_sewell", "SmallestLast", "FirstFit"]
        S += ["## Mean colours by set and scale\n", md(m[[c for c in keep if c in m.columns]], ".3f")]

    p = rd("paired_vs_dsatur.csv")
    if p is not None:
        sel = list(common.PAPER_SELECTED.values()) + ["DeepSeek_H1A", "LLaMA_H3A", "RLF", "RLF_legacy",
                                                      "DSATUR_brelaz", "DSATUR_sewell", "SmallestLast"]
        for s in ("TEST-A", "TEST-B"):
            t = p[(p.set == s) & (p.family == "all") & p.algorithm.isin(sel)]
            S += [f"## Paired comparison with DSATUR on {s} (B6, A6)\n",
                  md(t[["scale", "algorithm", "N", "mean_diff", "ci95_lo", "ci95_hi", "share_equal",
                        "share_better", "share_worse", "p_holm", "p_tost", "verdict"]])]

    opt = rd("e_a_optimism.csv")
    if opt is not None:
        S += ["## E-A selection optimism (VAL−TEST-A, relative to DSATUR)\n",
              "optimism = (VAL − DSATUR_VAL) − (TEST − DSATUR_TEST); positive = the VAL advantage "
              "did not carry over.\n",
              md(opt[opt.selected_in_paper][["scale", "heuristic", "VAL_minus_DSATUR", "TEST_minus_DSATUR",
                                             "optimism", "ci95_lo", "ci95_hi"]])]

    tt = rd("test_table_friedman.csv")
    if tt is not None:
        S += ["## Every Friedman test (D7; same 8 algorithms at every scale)\n",
              md(tt[["set", "scale", "N", "k", "statistic", "df", "p", "CD", "q_alpha"]], ".4g")]

    b2 = rd("e_b2_summary.csv")
    if b2 is not None:
        S += ["## E-B2 control arms on TEST-A (best of 5 on VAL per draw)\n", md(b2)]
        pos = rd("e_b2_llm_vs_random.csv")
        S += ["Share of random best-of-5 draws at least as good as each paper formula (TEST-A):\n", md(pos)]
        bud = os.path.join(O, "e_b2_budget.json")
        if os.path.exists(bud):
            S += ["Budget used: `" + json.dumps({k: v for k, v in json.load(open(bud)).items()
                                                 if k != "feature_scales"}) + "`\n"]

    g5 = rd("g5_perturbation.csv")
    if g5 is not None:
        g = (g5.assign(dVAL=g5["VAL_mean"] - g5["base_VAL"], dTEST=g5["TEST-A_mean"] - g5["base_TEST-A"])
             .groupby("label").agg(perturbations=("dVAL", "size"), best_dVAL=("dVAL", "min"),
                                   share_VAL_improves=("dVAL", lambda x: (x < 0).mean()),
                                   mean_dTEST=("dTEST", "mean")).reset_index())
        S += ["## G5 local-optimum check (coefficients × 0.75/0.9/1.1/1.25, one at a time)\n", md(g)]

    gp = rd("gaps_by_family_scale.csv")
    if gp is not None:
        for s in ("TEST-A", "PLANTED"):
            t = gp[(gp.set == s) & gp.algorithm.isin(["DSATUR", "LLaMA_H3", "Claude_H3A2A", "GPT4o_H4",
                                                       "DeepSeek_H1", "GPT51_H1", "RLF", "RLF_legacy",
                                                       "FirstFit"])]
            piv = t.pivot_table(index=["scale", "family"], columns="algorithm", values="rel_gap_pct").reset_index()
            S += [f"## Optimality gap (%) to chi / best-known UB, {s} (D3–D5)\n", md(piv, ".1f")]
        b = rd("bounds.csv")
        if b is not None:
            S += ["Bound status:\n", md(b.groupby(["set", "scale", "status"]).size().reset_index(name="N"), ".0f")]

    rt = rd("e_e_runtime_summary.csv")
    if rt is not None:
        t = rt[rt.method.isin(["DSATUR", "LLaMA_H3", "DeepSeek_H1", "GPT51_H1", "RLF", "RLF_legacy"])]
        S += ["## E-E runtime (median ms) and ratio to DSATUR within the same implementation\n", md(t)]
        f = rd("e_e_scaling_fits.csv")
        S += ["Log-log slope of runtime vs m:\n", md(f)]
        pa = rd("e_e_pareto.csv")
        S += ["Pareto status (TEST-A; colours vs incremental runtime):\n", md(pa)]

    fm = rd("e_f_mean_colors.csv")
    if fm is not None:
        S += ["## E-F GPU kernel ablation (emulator): mean colours\n", md(fm, ".2f"),
              "Mean rounds R:\n", md(rd("e_f_mean_rounds.csv"), ".1f")]
        idm = rd("e_f_identity_matrix.csv")
        llm = ["GPT4o", "GPT51", "Claude", "DeepSeek", "sat1e6_deg", "neg_sat", "neg_deg", "random"]
        S += ["Share of instances with identical colourings / counts (selected pairs):\n",
              md(idm[idm.a.isin(llm) & idm.b.isin(llm)])]
        S += ["rand() seed sensitivity (C5):\n", md(rd("e_f_rand_seed_variance.csv"))]

    g1 = rd("g1_effective_weights.csv")
    if g1 is not None:
        S += ["## G1 effective weights (share of |w|·SD) and score–sat rank correlation\n", md(g1)]
        S += ["## G2 ordering similarity with DSATUR\n", md(rd("g2_ordering_similarity.csv"))]
        S += ["## G7 cosine with DSATUR's direction (standardised)\n", md(rd("g7_dsatur_direction.csv"))]

    with open(os.path.join(O, "SUMMARY.md"), "w") as f:
        f.write("\n".join(S))
    print("wrote", os.path.join(O, "SUMMARY.md"))


if __name__ == "__main__":
    main()
