UNIVERSAL_PROMPT = """You are an expert in combinatorial optimisation and graph algorithms. Your task is to design five distinct vertex-ordering heuristics for the graph coloring problem.

Requirements for each heuristic:
- Compute a numerical priority score for every uncolored vertex v at each step of the greedy coloring process.
- The vertex with the highest score is colored next.
- Scores must be linear combinations of the following five features only:
  - degree(v) — total number of neighbours
  - saturation(v) — distinct colors in neighbourhood
  - uncolored_neighbors(v) — uncolored neighbour count
  - clustering_coefficient(v) — local clustering (∈ [0,1])
  - two_hop_neighbors(v) — vertices at distance 2
- No conditional statements, max/min operations, or non-linear transformations are permitted.
- Each heuristic must be meaningfully distinct from all of the following and from all other heuristics in the same submission:
  - Sequential baselines: DSATUR, First Fit, RLF
  - Parallel baselines: Jones-Plassmann, Luby's MIS, cuGraph

For each heuristic provide:
1. A named scoring formula with explicit numeric coefficients.
2. A one-sentence description of the design intuition.
3. A deterministic tie-breaking rule using the same feature vocabulary, with vertex identifier as the final tiebreaker."""

